import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const saved = JSON.parse(await readFile('tmp/flow-backup.json', 'utf8'));
  const today = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Asia/Taipei' }).format(new Date());
  saved.tradePositions = [{ ...saved.tradePositions[0], type: '空單', tradeDate: today, entryTaxPaid: 120 }];
  saved.presetOrders = []; saved.closedTrades = []; saved.presetFills = [];
  saved.cashTrackingEnabled = false;
  await page.addInitScript(data => localStorage.setItem('stock-simulator-workspace-v1', JSON.stringify(data)), saved);
  let failQuotes = false;
  await page.route('**/*', async route => {
    const url = route.request().url();
    if (url.startsWith('http://localhost:4200')) return route.continue();
    if (failQuotes) return route.abort();
    if (url.includes('/api/tpex/')) return route.fulfill({ json: { msgArray: [{ c:'2330', n:'台積電', d:today.replaceAll('-',''), t:'13:30:00', z:'90', y:'100', o:'100', h:'100', l:'90', v:'100' }] } });
    return route.fulfill({ json: { data: [], stat: 'OK' } });
  });
  await page.goto('http://localhost:4200');
  await page.getByRole('link', { name: '交易規劃', exact: true }).click();
  await page.getByRole('button', { name: '減少部位（賣出／回補）', exact: true }).click();
  const button = page.getByRole('button', { name: '記錄實際回補', exact: true });
  await button.click();
  const dialog = page.locator('#position-close-dialog');
  await dialog.waitFor({ state: 'visible' });
  await dialog.getByLabel('實際成交價', { exact: true }).fill('90');
  await dialog.getByLabel(/本次股數/).fill('401');
  assert.equal(await dialog.getByRole('button', { name:'確認記錄回補', exact:true }).isDisabled(), true);
  await dialog.getByLabel(/本次股數/).fill('200');
  await dialog.getByRole('button', { name:'確認記錄回補', exact:true }).click();
  await page.getByRole('button', { name:'立即儲存', exact:true }).click();
  const current = await page.evaluate(() => JSON.parse(localStorage.getItem('stock-simulator-workspace-v1')));
  assert.equal(current.tradePositions[0].shares, 200);
  assert.equal(current.closedTrades[0].shares, 200);
  assert.ok(current.closedTrades[0].realizedProfit > 0);
  assert.equal(current.closedTrades[0].exitPrice, 90);
  const before = JSON.stringify(current.tradePositions);
  await page.locator('input[type=file]').setInputFiles({ name:'invalid.json', mimeType:'application/json', buffer:Buffer.from('{broken') });
  await page.waitForFunction(() => [...document.querySelectorAll('[role="status"]')].some(el => (el.textContent ?? '').includes('匯入失敗：')));
  assert.equal(await page.getByRole('button', { name:'確認取代並還原', exact:true }).count(), 0);
  assert.equal(await page.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem('stock-simulator-workspace-v1')).tradePositions)), before);
  failQuotes = true;
  await page.getByRole('link', { name:'行情', exact:true }).click();
  await page.getByRole('button', { name:'重新整理行情', exact:true }).click();
  await page.locator('.hero-card .error-text').waitFor({ state:'visible', timeout:35000 });
  assert.ok((await page.locator('.hero-card .error-text').textContent()).includes('上次取得'));
  assert.equal(await page.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem('stock-simulator-workspace-v1')).tradePositions)), before);
  console.log('Verified mobile: partial short cover, excessive quantity blocked, invalid backup preserves holdings, quote failure retains last price');
} finally { await browser.close(); }
