import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import ExcelJS from 'exceljs';
const browser = await chromium.launch({headless:true});
await mkdir('tmp', { recursive: true });
try {
  const page = await browser.newPage({ viewport: process.argv.includes('--mobile') ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
  const today = new Intl.DateTimeFormat('sv-SE',{timeZone:'Asia/Taipei'}).format(new Date());
  await page.route('**/api/tpex/**', route => route.fulfill({json:{msgArray:[{c:'2330',n:'台積電',d:today.replaceAll('-',''),t:'13:30:00',z:'100',y:'99',o:'99',h:'105',l:'95',v:'100'}]}}));
  await page.route('https://www.twse.com.tw/**', route => route.fulfill({json:{title:'2330 台積電',data:Array.from({length:22},(_,i)=>[`115/09/${String(i+1).padStart(2,'0')}`,'100000','10000000','99','105','95','100','1','100','0'])}}));
  await page.goto('http://localhost:4200');
  await page.locator('#workspace-settings > details > summary').click();
  await page.getByText('現股資金流水（獨立估算）', { exact: true }).click();
  await page.getByLabel('起始流水餘額', { exact: true }).fill('100000');
  await page.getByRole('checkbox', { name: '啟用新現股成交的自動流水記錄', exact: true }).check();
  await page.getByRole('button',{name:'移除示意持倉',exact:true}).click();
  await page.getByRole('button',{name:'確認移除示意持倉',exact:true}).click();
  await page.getByRole('button',{name:'規劃預設單',exact:true}).click();
  const form=page.locator('.board-form');
  assert.equal(await page.locator('.board-visual').evaluate(el => el.open), false);
  assert.equal(await form.evaluate(el => !!(el.compareDocumentPosition(document.querySelector('.board-visual')) & Node.DOCUMENT_POSITION_FOLLOWING)), true);
  await form.getByLabel(/^下單單位/).selectOption('oddLot');
  assert.equal(await form.getByLabel('股數',{exact:true}).inputValue(),'1000');
  await form.getByLabel(/^下單單位/).selectOption('boardLot');
  await form.getByLabel('委託價',{exact:true}).fill('100');
  await form.getByLabel('停損價（選填）',{exact:true}).fill('95');
  await form.getByLabel('預計出場價（選填）',{exact:true}).fill('110');
  await form.getByLabel('股數',{exact:true}).fill('1000');
  await page.getByRole('button',{name:'重新整理行情',exact:true}).click();
  await page.getByRole('button',{name:'重新整理行情',exact:true}).waitFor({state:'visible'});
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].some(el => el.textContent.trim() === '載入中…'));
  assert.equal(await form.getByLabel('委託價',{exact:true}).inputValue(),'100');
  assert.equal(await form.getByLabel('停損價（選填）',{exact:true}).inputValue(),'95');
  assert.equal(await form.getByLabel('預計出場價（選填）',{exact:true}).inputValue(),'110');
  await form.locator('.form-submit').click();
  await page.getByRole('button',{name:'記錄實際成交',exact:true}).click();
  await page.locator('.preset-order-row').getByLabel(/本次成交股數/).fill('400');
  await page.getByRole('button',{name:'確認記錄成交',exact:true}).click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'下載資料備份',exact:true}).click();
  const backup=await downloadPromise;
  await backup.saveAs('tmp/flow-backup.json');
  const saved=JSON.parse(await readFile('tmp/flow-backup.json','utf8'));
  assert.equal(saved.tradePositions[0].shares,400);
  assert.equal(saved.presetOrders[0].shares,600);
  assert.equal(saved.presetFills.length,1);
  assert.equal(saved.cashMovements.length,1);
  assert.equal(saved.cashOpeningBalance,100000);
  assert.ok(Math.abs(saved.cashMovements[0].amount + 40034.2) < 0.0001);
  await page.getByRole('button',{name:'減少部位（賣出／回補）',exact:true}).click();
  await page.getByRole('button',{name:'規劃賣出委託',exact:true}).click();
  assert.equal(await form.getByLabel('股數',{exact:true}).inputValue(),'400');
  assert.equal(await form.getByLabel(/^下單目的/).inputValue(),'sell');
  await form.getByLabel(/^下單目的/).selectOption('sell');
  assert.equal(await form.locator('.order-risk-card').count(),0);
  assert.equal(await form.getByLabel('停損價（選填）',{exact:true}).count(),0);
  assert.ok((await form.textContent()).includes('預估出場淨損益'));
  await page.getByRole('button',{name:'記錄平倉',exact:true}).click();
  const close=page.locator('[aria-label="實際平倉確認"]');
  await close.waitFor({state:'visible'});
  assert.equal(await close.evaluate(el => el.matches(':modal')),true);
  assert.equal(await close.getByLabel('實際成交日期',{exact:true}).evaluate(el => el === document.activeElement),true);
  await close.getByLabel('實際成交價',{exact:true}).fill('110');
  await close.getByLabel(/本次股數/).fill('200');
  await close.getByRole('button',{name:'確認記錄平倉',exact:true}).click();
  await page.getByRole('button',{name:'立即儲存',exact:true}).click();
  const closedCash=await page.evaluate(() => JSON.parse(localStorage.getItem('stock-simulator-workspace-v1')).cashMovements);
  assert.equal(closedCash.length,2);
  assert.ok(Math.abs(closedCash[1].amount - (22000 - 18.81 - 66)) < 0.0001);
  await page.locator('input[type=file]').setInputFiles('tmp/flow-backup.json');
  await page.getByRole('button',{name:'確認取代並還原',exact:true}).click();
  await page.getByRole('button',{name:'記錄平倉',exact:true}).click();
  assert.equal(await page.locator('[aria-label="實際平倉確認"]').getByLabel(/本次股數/).inputValue(),'400');
  await page.getByRole('button',{name:'返回，不變更持倉',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'記錄平倉',exact:true}).evaluate(el => el === document.activeElement),true);
  await page.getByRole('button',{name:'記錄平倉',exact:true}).click();
  await page.locator('#position-close-dialog').waitFor({state:'visible'});
  await page.keyboard.press('Escape');
  await page.locator('#position-close-dialog').waitFor({state:'detached'});
  assert.equal(await page.getByRole('button',{name:'記錄平倉',exact:true}).evaluate(el => el === document.activeElement),true);
  const excelPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:/匯出成交紀錄/}).click();
  await (await excelPromise).saveAs('tmp/flow-fills.xlsx');
  const workbook=new ExcelJS.Workbook();
  await workbook.xlsx.readFile('tmp/flow-fills.xlsx');
  assert.equal(workbook.getWorksheet('實際成交紀錄').getCell('H2').value,400);
  console.log('Verified: create → partial fill + cash → backup → partial close + cash → restore → Excel values');
} finally {await browser.close();}
